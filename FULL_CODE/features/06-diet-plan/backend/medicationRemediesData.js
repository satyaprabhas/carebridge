function evaluateMedicationRemedies(medicinesList) {
  const remedies = [];
  const seenPatterns = new Set();

  if (Array.isArray(medicinesList)) {
    medicinesList.forEach(m => {
      const name = typeof m === 'string' ? m : (m?.name || m?.medicineName || m?.medicine || m?.drug || '');
      if (!name || name.trim().length === 0) return;

      for (let i = 0; i < MEDICATION_REMEDIES.length; i++) {
        const rem = MEDICATION_REMEDIES[i];
        if (rem.pattern.test(name)) {
          if (!seenPatterns.has(rem.name)) {
            seenPatterns.add(rem.name);
            remedies.push({
              medName: name,
              remedyTitle: rem.name,
              sideEffect: rem.sideEffect,
              remedy: rem.remedy,
              include: rem.include,
              avoid: rem.avoid,
              warning: rem.warning || ''
            });
          }
          break;
        }
      }
    });
  }

  return remedies;
}

if (typeof window !== 'undefined') {
  window.MEDICATION_REMEDIES = MEDICATION_REMEDIES;
  window.evaluateMedicationRemedies = evaluateMedicationRemedies;
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = {
    MEDICATION_REMEDIES,
    evaluateMedicationRemedies
  };
}
